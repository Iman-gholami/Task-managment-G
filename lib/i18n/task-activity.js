import { translate } from "./messages.js";
import { taskDate } from "../task-date.js";

const ACTIONS_FA = {
  "created the task": "تسک را ایجاد کرد",
  "deleted the task": "تسک را حذف کرد",
  "completed the task (review not required)": "تسک را بدون نیاز به بازبینی تکمیل کرد",
  "started the task": "کار را شروع کرد",
  "submitted it for review": "تسک را برای بازبینی ارسال کرد",
  "approved it": "تسک را تأیید کرد",
  "returned it for changes": "تسک را برای اصلاح بازگرداند",
  "reopened the task": "تسک را دوباره باز کرد",
  "unblocked the task": "مانع تسک را رفع کرد",
  "resumed work": "کار را از سر گرفت",
  "marked it blocked": "تسک را متوقف اعلام کرد",
  "cancelled the task": "تسک را لغو کرد",
  "restored the task": "تسک را بازگردانی کرد",
  "enabled manager review": "بازبینی مدیر را فعال کرد",
  "disabled manager review": "بازبینی مدیر را غیرفعال کرد",
  "removed the deadline": "سررسید را حذف کرد",
};

// Historical events are generated by the server, but can embed names and filenames.
// Translate only recognized event patterns and retain embedded user text unchanged.
export function taskActivityText(text, locale) {
  if (locale !== "fa" || typeof text !== "string") return text;
  return text.split(" · ").map((part) => {
    if (ACTIONS_FA[part]) return ACTIONS_FA[part];
    let match;
    if ((match = /^quality: (Excellent|Good|Acceptable|Needs Improvement)$/.exec(part))) return `کیفیت: ${translate(locale, match[1])}`;
    if ((match = /^complexity: (Simple|Medium|Complex|Advanced) → (Simple|Medium|Complex|Advanced)$/.exec(part))) return `پیچیدگی: ${translate(locale, match[1])} ← ${translate(locale, match[2])}`;
    if ((match = /^priority (Low|Normal|High|Critical) → (Low|Normal|High|Critical)$/.exec(part))) return `اولویت ${translate(locale, match[1])} ← ${translate(locale, match[2])}`;
    if ((match = /^deadline → (\d{4}-\d{2}-\d{2})$/.exec(part))) return `سررسید ← ${taskDate(match[1], locale)}`;
    if ((match = /^reassigned to (.+)$/.exec(part))) return `به ${match[1]} واگذار شد`;
    if ((match = /^attached (.+)$/.exec(part))) return `فایل ${match[1]} را پیوست کرد`;
    return part;
  }).join(" · ");
}
