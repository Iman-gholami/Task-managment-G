export function translate(locale, text) {
  if (typeof text !== "string") return text;
  return locale === "fa" ? (EN_TO_FA[text] ?? text) : (FA_TO_EN[text] ?? text);
}

export function normalizeLocale(value) {
  return value === "fa" ? "fa" : "en";
}
