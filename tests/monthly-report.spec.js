const { test, expect } = require("@playwright/test");
const JSZip = require("jszip");
const fs = require("node:fs/promises");
const ADMIN = { email:"test-admin@local.invalid", password:"E2E-Only-Admin-2026!" };
const PW = "Monthly-Only-2026!";
function currentMonth() {
  const parts = new Intl.DateTimeFormat("en-US-u-ca-persian-nu-latn", { timeZone:"Asia/Tehran", year:"numeric", month:"2-digit" }).formatToParts(new Date());
  const values = Object.fromEntries(parts.map((p) => [p.type,p.value])); return `${values.year}-${values.month}`;
}
test("automatic comparisons and monthly exports are scoped and usable", async ({ page, context, baseURL }) => {
  await context.addCookies([{ name:"so.locale", value:"fa", url:baseURL }]);
  expect((await page.request.post("/api/auth/login", { data:ADMIN })).ok()).toBeTruthy();
  const create = async (name,email,role,team) => {
    const response = await page.request.post("/api/members", { data:{ name,email,role,team,province:"قم",password:PW } });
    expect(response.status()).toBe(201); return (await response.json()).user;
  };
  await create("Monthly SOC Manager","monthly-soc@local.invalid","soc_manager","SOC");
  const analyst = await create("Monthly SOC Analyst","monthly-l2@local.invalid","analyst","SOC · L2");
  const intelligence = await create("Monthly TI Analyst","monthly-ti@local.invalid","analyst","Threat Intelligence");
  await create("Monthly Observer","monthly-observer@local.invalid","observer","Security Department");
  expect((await page.request.post("/api/tasks", { data:{ title:"Monthly SOC investigation",description:"Detailed task evidence",a:analyst.id,prio:"normal",cx:2 } })).status()).toBe(201);
  await page.goto("/analytics/compare");
  await expect(page.getByTestId("automatic-team-comparison")).toContainText("SOC");
  await expect(page.getByTestId("automatic-people-comparison")).toContainText("Monthly SOC Analyst");
  await expect(page.getByTestId("automatic-people-comparison")).toContainText("Monthly TI Analyst");
  await expect(page.getByTestId("compare-add")).not.toBeVisible();
  await page.getByTestId("monthly-report-button").click();
  const drawer = page.getByRole("dialog", { name:"گزارش ماهانه" });
  await drawer.getByTestId("monthly-report-month").fill(currentMonth());
  await drawer.getByLabel("تیم",{exact:true}).selectOption("soc");
  await drawer.getByLabel("لایه SOC").selectOption("L2");
  await expect(drawer.getByLabel("افراد")).not.toContainText("Monthly TI Analyst");
  await drawer.getByLabel("افراد").selectOption(analyst.id);
  const preview = await page.request.get(await drawer.getByRole("link",{name:"نمایش HTML"}).getAttribute("href"));
  expect(preview.status()).toBe(200); expect(preview.headers()["content-security-policy"]).toContain("default-src 'none'");
  const previewHtml = await preview.text(); expect(previewHtml).toContain("Monthly SOC investigation"); expect(previewHtml).not.toContain("Monthly TI Analyst");
  const [download] = await Promise.all([page.waitForEvent("download"), drawer.getByTestId("monthly-report-download").click()]);
  const zip = await JSZip.loadAsync(await fs.readFile(await download.path()));
  expect(Object.keys(zip.files).filter((n) => n.endsWith(".html"))).toHaveLength(1);
  expect(Object.keys(zip.files).filter((n) => n.endsWith(".xlsx"))).toHaveLength(1);
  await page.request.post("/api/auth/login", { data:{email:"monthly-soc@local.invalid",password:PW} });
  const soc = await page.request.get(`/api/analytics/monthly-report?month=${currentMonth()}&format=html`), socHtml = await soc.text();
  expect(soc.status()).toBe(200); expect(socHtml).toContain("Monthly SOC Analyst"); expect(socHtml).toContain("Monthly TI Analyst");
  expect((await page.request.get(`/api/analytics/monthly-report?month=${currentMonth()}&person=${intelligence.id}`)).status()).toBe(200);
  const socFacts = await (await page.request.get("/api/analytics")).json();
  expect(socFacts.people.some((person) => person.id === intelligence.id)).toBeFalsy();
  await page.goto("/analytics");
  await page.getByTestId("monthly-report-button").click();
  const socDrawer = page.getByRole("dialog", { name:"گزارش ماهانه" });
  await socDrawer.getByTestId("monthly-report-month").fill(currentMonth());
  await socDrawer.getByLabel("تیم",{exact:true}).selectOption("ti");
  await socDrawer.getByLabel("افراد").selectOption(intelligence.id);
  const tiReport = await page.request.get(await socDrawer.getByRole("link",{name:"نمایش HTML"}).getAttribute("href"));
  const tiHtml = await tiReport.text();
  expect(tiReport.status()).toBe(200); expect(tiHtml).toContain("Monthly TI Analyst"); expect(tiHtml).not.toContain("Monthly SOC Analyst");
  await page.request.post("/api/auth/login", { data:{email:"monthly-l2@local.invalid",password:PW} });
  expect((await page.request.get(`/api/analytics/monthly-report?month=${currentMonth()}`)).status()).toBe(403);
  await page.request.post("/api/auth/login", { data:{email:"monthly-observer@local.invalid",password:PW} });
  expect((await page.request.get(`/api/analytics/monthly-report?month=${currentMonth()}`)).status()).toBe(403);
});
